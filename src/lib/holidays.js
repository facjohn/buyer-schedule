const BY_DATE = new Map();
for (const [year, list] of Object.entries(TABLE)) for (const [md, name] of list) BY_DATE.set(`${year}-${md}`, name);

/** 달력 칸은 좁아서(폰에서 4글자까지) 짧은 이름 */
export function shortHoliday(name) {
  if (name.startsWith('대체공휴일')) return '대체휴일';
  if (name.startsWith('임시공휴일')) return '임시휴일';
  if (name.includes('선거')) return '선거일';
  if (name.startsWith('설날')) return '설날';
  if (name.startsWith('추석')) return '추석';
  if (name.startsWith('부처님오신날')) return '석탄일';
  return name.split('·')[0];
}

export const HOLIDAY_YEARS = Object.keys(TABLE).map(Number);
const LAST_YEAR = Math.max(...HOLIDAY_YEARS);

/** 'yyyy-MM-dd'가 공휴일이면 { name, short }, 아니면 null */
export function holidayOf(iso) {
  if (!iso) return null;
  const year = Number(iso.slice(0, 4));
  const name = year <= LAST_YEAR
    ? BY_DATE.get(iso) // 표보다 앞의 해(2024년 이전)는 쓰지 않는다
    : (FIXED.find(([md]) => md === iso.slice(5)) || [])[1];
  return name ? { name, short: shortHoliday(name) } : null;
}
